import { useEffect, useId, useState } from 'react'

// Renders a Mermaid diagram from the project docs. The library is loaded on demand;
// if it fails to load or parse, the diagram source is shown instead.
export default function Mermaid({ chart }) {
  const id = `mmd-${useId().replace(/[^a-zA-Z0-9]/g, '')}`
  const [svg, setSvg] = useState(null)
  const [failed, setFailed] = useState(false)

  useEffect(() => {
    let cancelled = false
    ;(async () => {
      try {
        const mermaid = (await import('mermaid')).default
        mermaid.initialize({ startOnLoad: false, securityLevel: 'strict', theme: 'dark' })
        const { svg: out } = await mermaid.render(id, chart)
        if (!cancelled) setSvg(out)
      } catch {
        if (!cancelled) setFailed(true)
      }
    })()
    return () => { cancelled = true }
  }, [chart, id])

  if (failed) return <pre className="code"><code>{chart}</code></pre>
  if (!svg) return <p className="muted" role="status">Rendering diagram…</p>
  // The SVG is generated by Mermaid (securityLevel "strict") from repository documents.
  return <div className="mermaid-out" dangerouslySetInnerHTML={{ __html: svg }} />
}
